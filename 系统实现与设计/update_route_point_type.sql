-- =============================================
-- 路线点位类型优化升级脚本
-- 执行日期：2026-01-19
-- 功能说明：
--   1. 更新route_point表的point_type字段注释
--   2. 扩展点位类型定义，新增类型5（路线轨迹点）
--   3. 优化数据存储结构，消除起终点冗余
-- =============================================

USE hiking_system;

-- 1. 更新route_point表的point_type字段注释
ALTER TABLE `route_point`
MODIFY COLUMN `point_type` TINYINT NOT NULL DEFAULT 1
COMMENT '点位类型：1途经点 2风险点 3休息点 4补给点 5路线轨迹点';

-- 2. 查看更新后的表结构
DESC route_point;

-- =============================================
-- 点位类型说明文档
-- =============================================
-- 类型1: 途经点 (Waypoint)
--   - 用户手动标注的重要位置
--   - 前端展示：青色➕标记
--   - 用途：标记观景台、岔路口等重要地点
--
-- 类型2: 风险点 (Risk Point)
--   - 需要特别注意的危险区域
--   - 前端展示：黄色⚠️标记
--   - 字段：risk_level (1低2中3高), risk_tip (风险提示)
--   - 用途：陡坡、悬崖、落石区等危险地段
--
-- 类型3: 休息点 (Rest Point)
--   - 建议休息的地方
--   - 前端展示：紫色☕标记
--   - 用途：标记适合休息的平台、亭子等
--
-- 类型4: 补给点 (Supply Point)
--   - 可以补充水食的地方
--   - 前端展示：橙色🏪标记
--   - 用途：商店、补水点、便利店等
--
-- 类型5: 路线轨迹点 (Track Point)
--   - 用于绘制路线的GPS轨迹点
--   - 前端展示：蓝色📍标记
--   - 用途：连接起终点的中间轨迹，用于绘制路线线条
--   - 特点：系统自动生成，用户绘制路线时产生
-- =============================================

-- 3. 验证数据（可选）
-- 查看当前各类型点位的数量分布
SELECT
    point_type,
    CASE point_type
        WHEN 1 THEN '途经点'
        WHEN 2 THEN '风险点'
        WHEN 3 THEN '休息点'
        WHEN 4 THEN '补给点'
        WHEN 5 THEN '路线轨迹点'
        ELSE '未知类型'
    END AS type_name,
    COUNT(*) AS count
FROM route_point
GROUP BY point_type
ORDER BY point_type;

-- 4. 检查是否有异常数据
SELECT * FROM route_point WHERE point_type NOT IN (1, 2, 3, 4, 5);

-- =============================================
-- 升级说明
-- =============================================
-- 【重要变更】
-- 1. 起点和终点不再存储在route_point表中
--    - 旧方案：起终点既存在route表，也作为route_point表的首尾记录
--    - 新方案：起终点仅存储在route表的专用字段中
--    - 影响：消除数据冗余，避免数据不一致问题
--
-- 2. 路线轨迹点使用新类型5
--    - 旧方案：路线绘制的轨迹点使用point_type=1
--    - 新方案：路线轨迹点使用point_type=5，与用户标注的途经点区分
--    - 影响：可以准确区分系统生成的轨迹点和用户标注的重要点位
--
-- 3. 新增3种点位类型的完整支持
--    - 风险点(2)：用于安全预警
--    - 休息点(3)：用于体力规划
--    - 补给点(4)：用于物资规划
--    - 前端已实现完整的CRUD功能
--
-- 【兼容性】
-- - 本次升级仅修改字段注释，不改变表结构
-- - 不影响现有数据
-- - 向后兼容旧版本创建的路线数据
-- =============================================

SELECT '路线点位类型升级脚本执行完成！' AS message;
